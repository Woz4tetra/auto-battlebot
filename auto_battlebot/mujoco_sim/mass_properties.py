"""Loader for a robot's simulation/assets/robots/<robot>/mass_properties.toml.

Mr Stabs Mk2's file is generated by playground/calibration/lump_mr_stabs_mass_properties.py from
the Onshape export, in the FLU body frame at the axle midpoint. Mrs Buff Mk3's comes from
playground/calibration/build_mrs_buff_mk3_model.py, in the FLU frame at her footprint centre at
axle height: her motors drive the back wheels, and belts drive the front ones 1:1 (followers).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from auto_battlebot.compat import tomllib

ROBOTS_DIR = Path(__file__).resolve().parents[2] / "simulation/assets/robots"
ASSET_DIR = ROBOTS_DIR / "mr_stabs_mk2"
DEFAULT_PATH = ASSET_DIR / "mass_properties.toml"


def asset_dir(robot: str) -> Path:
    """simulation/assets/robots/<robot>, which holds mass_properties.toml and collision/."""
    path = ROBOTS_DIR / robot
    if not (path / "mass_properties.toml").exists():
        raise FileNotFoundError(f"no mass_properties.toml under {path}")
    return path


@dataclass(frozen=True)
class Body:
    mass: float
    com: np.ndarray  # (3,) m
    fullinertia: np.ndarray  # (6,) Ixx Iyy Izz Ixy Ixz Iyz about the COM, kg m^2

    @classmethod
    def from_table(cls, table: dict[str, Any]) -> Body:
        return cls(
            mass=float(table["mass_kg"]),
            com=np.asarray(table["com_m"], dtype=float),
            fullinertia=np.asarray(table["fullinertia_kg_m2"], dtype=float),
        )


@dataclass(frozen=True)
class TagMount:
    tag_id: int
    upside_down: bool  # faces the floor when the robot is upright
    translation: np.ndarray  # (3,) tag center in the body frame
    rotation: np.ndarray  # (3, 3) R_body_tag
    size_m: float

    def body_from_tag(self) -> np.ndarray:
        out = np.eye(4)
        out[:3, :3] = self.rotation
        out[:3, 3] = self.translation
        return out


@dataclass(frozen=True)
class Weapon:
    """A disk weapon's sweep: a cylinder about body y, the space the disk fills when it spins."""

    center: np.ndarray  # (3,) spin axis point at the disk's mid-plane, body frame
    radius: float  # largest disk radius about the axis
    half_width: float  # half the disk thickness along the axis


@dataclass(frozen=True)
class MassProperties:
    chassis: Body
    wheel_left: Body
    wheel_right: Body
    track_half_width: float
    wheel_radius: float
    tread_width: float
    gear_ratio: float
    motor_kt: float
    rotor_inertia: float
    tags: dict[int, TagMount]
    axle_x: float = 0.0  # driven wheels' axle, body x
    follower_axle_x: float | None = None  # belt-coupled wheels' axle, or None for none
    weapon: Weapon | None = None

    @property
    def reflected_inertia(self) -> float:
        """Rotor inertia seen at the wheel through the gearbox, N^2 J_r."""
        return self.gear_ratio**2 * self.rotor_inertia

    @property
    def total_mass(self) -> float:
        wheels = self.wheel_left.mass + self.wheel_right.mass
        return self.chassis.mass + wheels * (2 if self.follower_axle_x is not None else 1)


def load(path: Path = DEFAULT_PATH) -> MassProperties:
    data = tomllib.loads(Path(path).read_text())
    geometry = data["geometry"]
    drivetrain = data["drivetrain"]
    tags = {
        int(key): TagMount(
            tag_id=int(key),
            upside_down=bool(t["upside_down"]),
            translation=np.asarray(t["translation_m"], dtype=float),
            rotation=np.asarray(t["rotation"], dtype=float),
            size_m=float(t["size_m"]),
        )
        for key, t in data.get("tags", {}).items()
    }
    weapon = None
    if "weapon" in data:
        w = data["weapon"]
        weapon = Weapon(
            center=np.asarray(w["sweep_center_m"], dtype=float),
            radius=float(w["sweep_radius_m"]),
            half_width=float(w["sweep_half_width_m"]),
        )
    follower = geometry.get("follower_axle_x_m")
    return MassProperties(
        chassis=Body.from_table(data["chassis"]),
        wheel_left=Body.from_table(data["wheel_left"]),
        wheel_right=Body.from_table(data["wheel_right"]),
        track_half_width=float(geometry["track_half_width_m"]),
        wheel_radius=float(geometry["wheel_radius_m"]),
        tread_width=float(geometry["tread_width_m"]),
        gear_ratio=float(drivetrain["gear_ratio"]),
        motor_kt=float(drivetrain["motor_kt_nm_per_a"]),
        rotor_inertia=float(drivetrain["rotor_inertia_kg_m2"]),
        tags=tags,
        axle_x=float(geometry.get("axle_x_m", 0.0)),
        follower_axle_x=None if follower is None else float(follower),
        weapon=weapon,
    )
