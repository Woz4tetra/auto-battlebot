#!/usr/bin/env node
// Generates src/generated/protocol.ts from the remote protocol table.
//
//   node scripts/gen-protocol.mjs [protocol.json]
//
// With no argument it runs ../build/remote_protocol_dump, then ../build-test/remote_protocol_dump.
//
// Type names come from the schema title `auto_battlebot.<kind>.<Name>`:
//   top-level status schema   -> <Name>Status    (auto_battlebot.status.System -> SystemStatus)
//   top-level command schema  -> <Name>Command   (auto_battlebot.command.SetAutonomy -> SetAutonomyCommand)
//   nested object schema      -> <Name>          (auto_battlebot.status.TrackedRobot -> TrackedRobot)

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import * as prettier from "prettier";

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = resolve(webDir, "src/generated/protocol.ts");

function loadProtocol() {
  const arg = process.argv[2];
  if (arg) return JSON.parse(readFileSync(arg, "utf8"));
  const candidates = ["../build/remote_protocol_dump", "../build-test/remote_protocol_dump"].map(
    (p) => resolve(webDir, p),
  );
  for (const exe of candidates) {
    if (existsSync(exe)) return JSON.parse(execFileSync(exe, { encoding: "utf8" }));
  }
  console.error(
    `gen-protocol: no protocol file given and none of these exist:\n  ${candidates.join("\n  ")}`,
  );
  process.exit(1);
}

function baseName(title) {
  const parts = String(title).split(".");
  return parts[parts.length - 1];
}

/** Returns a copy of the schema with every title rewritten to its TypeScript name. */
function renameTitles(schema, suffix) {
  const walk = (node, top) => {
    if (Array.isArray(node)) return node.map((n) => walk(n, false));
    if (node === null || typeof node !== "object") return node;
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "title") out.title = top ? baseName(value) + suffix : baseName(value);
      else if (key === "properties") {
        out.properties = Object.fromEntries(
          Object.entries(value).map(([k, v]) => [k, walk(v, false)]),
        );
      } else out[key] = walk(value, false);
    }
    return out;
  };
  return walk(schema, true);
}

const compileOptions = {
  bannerComment: "",
  additionalProperties: false,
  format: false,
  declareExternallyReferenced: true,
  enableConstEnums: false,
};

/** Splits json2ts output into `export ...` declarations keyed by name, keeping the first copy. */
function collect(ts, decls) {
  for (const block of ts.split(/^(?=export )/m)) {
    const match = block.match(/^export (?:interface|type) (\w+)/);
    if (!match) continue;
    if (!decls.has(match[1])) decls.set(match[1], block.trim());
  }
}

const protocol = loadProtocol();
const decls = new Map();
const statusRows = [];
const commandRows = [];

for (const row of protocol.status) {
  const schema = renameTitles(row.schema, "Status");
  collect(await compile(schema, schema.title, compileOptions), decls);
  statusRows.push({ ...row, typeName: schema.title });
}
for (const row of protocol.commands) {
  const schema = renameTitles(row.schema, "Command");
  collect(await compile(schema, schema.title, compileOptions), decls);
  commandRows.push({ ...row, typeName: schema.title });
}

const q = JSON.stringify;
const lines = [
  "// Generated by web/scripts/gen-protocol.mjs from remote_protocol_dump. Do not edit.",
  "// Source of truth: include/remote/protocol.hpp and include/remote/messages.hpp.",
  "",
  ...[...decls.values()].flatMap((d) => [d, ""]),
  "export type StatusMessages = {",
  ...statusRows.map((r) => `  ${q(r.topic)}: ${r.typeName};`),
  "};",
  "",
  "export type CommandPayloads = {",
  ...commandRows.map((r) => `  ${q(r.topic)}: ${r.typeName};`),
  "};",
  "",
  "export type StatusTopic = keyof StatusMessages;",
  "export type CommandTopic = keyof CommandPayloads;",
  "",
  "/** Status topic -> schema name. */",
  "export const STATUS_SCHEMAS = {",
  ...statusRows.map((r) => `  ${q(r.topic)}: ${q(r.schema_name)},`),
  "} as const satisfies Record<StatusTopic, string>;",
  "",
  "/** Status topic -> whether the relay latches it for late subscribers. */",
  "export const STATUS_LATCHED = {",
  ...statusRows.map((r) => `  ${q(r.topic)}: ${r.latch},`),
  "} as const satisfies Record<StatusTopic, boolean>;",
  "",
  "/** Command topic -> schema name. */",
  "export const COMMAND_SCHEMAS = {",
  ...commandRows.map((r) => `  ${q(r.topic)}: ${q(r.schema_name)},`),
  "} as const satisfies Record<CommandTopic, string>;",
  "",
];

const config = (await prettier.resolveConfig(outPath)) ?? {};
const formatted = await prettier.format(lines.join("\n"), { ...config, filepath: outPath });
mkdirSync(dirname(outPath), { recursive: true });
const previous = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
if (previous !== formatted) {
  writeFileSync(outPath, formatted);
  console.log(`gen-protocol: wrote ${outPath}`);
} else {
  console.log(`gen-protocol: ${outPath} unchanged`);
}
