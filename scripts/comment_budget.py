@dataclass
class FileResult:
    """Counted and malformed comment lines of one file."""

    path: str
    lines: list[str]
    counted: list[tuple[int, str]]
    malformed: list[int]

    @property
    def count(self) -> int:
        """Number of counted comment lines."""
        return len(self.counted)

    def text(self, line: int) -> str:
        """Source text of a 1-based line."""
        return self.lines[line - 1].strip() if 0 < line <= len(self.lines) else ""


class _CScanner:
    """Finds comment spans in C, C++, JS, and TS source, skipping literals."""

    def __init__(self, text: str, cxx: bool) -> None:
        self.text = text
        self.cxx = cxx
        self.i = 0
        self.spans: list[Span] = []

    def run(self) -> list[Span]:
        """Scan the whole text."""
        n = len(self.text)
        while self.i < n:
            self.i = self._step(self.text[self.i])
        return self.spans

    def _step(self, c: str) -> int:
        text, i = self.text, self.i
        if text.startswith("//", i):
            end = _line_end(text, i)
            self.spans.append((i, end))
            return end
        if text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = len(text) if end < 0 else end + 2
            self.spans.append((i, end))
            return end
        if c == '"':
            return self._raw_string(i) if self._is_raw(i) else _skip_quoted(text, i, '"')
        if c == "'":
            return i + 1 if self._is_digit_separator(i) else _skip_quoted(text, i, "'")
        if c == "`" and not self.cxx:
            return _skip_quoted(text, i, "`", multiline=True)
        return i + 1

    def _token_start(self, i: int) -> int:
        j = i
        while j > 0 and (self.text[j - 1].isalnum() or self.text[j - 1] in "_."):
            j -= 1
        return j

    def _is_digit_separator(self, i: int) -> bool:
        if not self.cxx or i == 0 or not self.text[i - 1].isalnum():
            return False
        return self.text[self._token_start(i)].isdigit()

    def _is_raw(self, i: int) -> bool:
        if not self.cxx or i == 0 or self.text[i - 1] != "R":
            return False
        prefix = self.text[self._token_start(i) : i]
        return prefix in ("R", "u8R", "uR", "UR", "LR")

    def _raw_string(self, i: int) -> int:
        open_paren = self.text.find("(", i + 1)
        if open_paren < 0:
            return len(self.text)
        delimiter = ")" + self.text[i + 1 : open_paren] + '"'
        end = self.text.find(delimiter, open_paren + 1)
        return len(self.text) if end < 0 else end + len(delimiter)


class _ShellScanner:
    """Finds comment spans in shell source, skipping quotes and heredoc bodies."""

    WORD_BREAKS = " \t\n;&|()"

    def __init__(self, text: str) -> None:
        self.text = text
        self.i = 0
        self.spans: list[Span] = []
        self.heredocs: list[tuple[str, bool]] = []

    def run(self) -> list[Span]:
        """Scan the whole text."""
        self._code(in_subshell=False)
        return self.spans

    def _code(self, in_subshell: bool) -> None:
        depth = 0
        while self.i < len(self.text):
            c = self.text[self.i]
            if c == ")" and in_subshell:
                self.i += 1
                if depth == 0:
                    return
                depth -= 1
                continue
            depth += c == "("
            self._step(c)

    def _step(self, c: str) -> None:
        text, i = self.text, self.i
        if c == "\n":
            self.i = self._skip_heredocs(i + 1)
        elif c == "#" and (i == 0 or text[i - 1] in self.WORD_BREAKS):
            self.i = _line_end(text, i)
            self.spans.append((i, self.i))
        elif c == "\\":
            self.i = i + 2
        elif c == "'":
            self.i = _skip_until(text, i + 1, "'")
        elif c == '"':
            self._double_quoted()
        elif c == "`":
            self.i = _skip_quoted(text, i, "`", multiline=True)
        elif text.startswith("$'", i):
            self.i = _skip_quoted(text, i + 1, "'", multiline=True)
        elif text.startswith("<<", i) and not text.startswith("<<<", i):
            self._heredoc_start()
        else:
            self.i = i + 1

    def _double_quoted(self) -> None:
        text = self.text
        self.i += 1
        while self.i < len(text):
            c = text[self.i]
            if c == '"':
                self.i += 1
                return
            if text.startswith("$(", self.i):
                self.i += 2
                self._code(in_subshell=True)
            elif c == "`":
                self.i = _skip_quoted(text, self.i, "`", multiline=True)
            else:
                self.i += 2 if c == "\\" else 1

    def _heredoc_start(self) -> None:
        match = re.compile(r"<<(-?)\s*(['\"]?)([A-Za-z_]\w*)\2").match(self.text, self.i)
        if match is None:
            self.i += 2
            return
        self.heredocs.append((match.group(3), match.group(1) == "-"))
        self.i = match.end()

    def _skip_heredocs(self, i: int) -> int:
        text = self.text
        for delimiter, strip_tabs in self.heredocs:
            while i < len(text):
                end = _line_end(text, i)
                line = text[i:end]
                i = end + 1
                if (line.lstrip("\t") if strip_tabs else line) == delimiter:
                    break
        self.heredocs.clear()
        return i


def _line_end(text: str, i: int) -> int:
    end = text.find("\n", i)
    return len(text) if end < 0 else end


def _skip_until(text: str, i: int, terminator: str) -> int:
    end = text.find(terminator, i)
    return len(text) if end < 0 else end + len(terminator)


def _skip_quoted(text: str, i: int, quote: str, multiline: bool = False) -> int:
    """Index just past the literal opened at i, honouring backslash escapes."""
    j = i + 1
    n = len(text)
    while j < n:
        c = text[j]
        if c == quote:
            return j + 1
        if c == "\n" and not multiline:
            return j
        j += 2 if c == "\\" else 1
    return n


def _hash_spans(text: str, yaml: bool) -> list[Span]:
    """Comment spans for TOML and YAML."""
    spans: list[Span] = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        boundary = i == 0 or text[i - 1] in " \t\n"
        if c == "#" and (boundary or not yaml):
            end = _line_end(text, i)
            spans.append((i, end))
            i = end
        elif c in "\"'" and (not yaml or i == 0 or text[i - 1] in " \t\n[{,:-"):
            i = _skip_hash_string(text, i, triple=not yaml)
        else:
            i += 1
    return spans


def _skip_hash_string(text: str, i: int, triple: bool) -> int:
    quote = text[i]
    if triple and text.startswith(quote * 3, i):
        return _skip_until(text, i + 3, quote * 3)
    if quote == "'":
        j = i + 1
        while j < len(text) and text[j] not in "'\n":
            j += 1
        return j + 1 if j < len(text) and text[j] == "'" else j
    return _skip_quoted(text, i, '"')


def _cmake_spans(text: str) -> list[Span]:
    """Comment spans for CMake, including bracket comments."""
    spans: list[Span] = []
    bracket = re.compile(r"\[(=*)\[")
    i = 0
    while i < len(text):
        c = text[i]
        opened = bracket.match(text, i + 1) if c == "#" else bracket.match(text, i)
        if c == "#":
            close = "]" + opened.group(1) + "]" if opened else "\n"
            end = text.find(close, i)
            end = len(text) if end < 0 else end + (len(close) if opened else 0)
            spans.append((i, end))
            i = end
        elif opened:
            i = _skip_until(text, opened.end(), "]" + opened.group(1) + "]")
        else:
            i = _skip_quoted(text, i, '"', multiline=True) if c == '"' else i + 1
    return spans


def _ini_spans(text: str) -> list[Span]:
    """Comment spans for INI files: whole lines starting with # or ;."""
    spans: list[Span] = []
    offset = 0
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped[:1] in ("#", ";"):
            spans.append((offset + len(line) - len(stripped), offset + len(line)))
        offset += len(line) + 1
    return spans


SCANNERS: dict[str, Callable[[str], list[Span]]] = {
    "cxx": lambda text: _CScanner(text, cxx=True).run(),
    "js": lambda text: _CScanner(text, cxx=False).run(),
    "shell": lambda text: _ShellScanner(text).run(),
    "toml": lambda text: _hash_spans(text, yaml=False),
    "yaml": lambda text: _hash_spans(text, yaml=True),
    "cmake": _cmake_spans,
    "ini": _ini_spans,
}


def spans_to_segments(text: str, spans: list[Span]) -> dict[int, list[str]]:
    """Map 1-based line numbers to the comment text found on them."""
    starts = [0] + [m.end() for m in re.finditer("\n", text)]
    segments: dict[int, list[str]] = {}
    for start, end in spans:
        first = bisect.bisect_right(starts, start)
        for k, part in enumerate(text[start:end].split("\n")):
            segments.setdefault(first + k, []).append(part)
    return segments


def python_segments(text: str) -> tuple[dict[int, list[str]], list[int]]:
    """Comment segments from tokenize and multi-line docstring lines from ast."""
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tree = ast.parse(text)
    except (SyntaxError, tokenize.TokenError):
        return spans_to_segments(text, _hash_spans(text, yaml=False)), []
    segments: dict[int, list[str]] = {}
    for token in tokens:
        if token.type == tokenize.COMMENT:
            segments.setdefault(token.start[0], []).append(token.string)
    return segments, _docstring_lines(tree)


def _docstring_lines(tree: ast.Module) -> list[int]:
    owners = (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
    lines: list[int] = []
    for node in ast.walk(tree):
        if not isinstance(node, owners) or not node.body:
            continue
        first = node.body[0]
        if not isinstance(first, ast.Expr) or not isinstance(first.value, ast.Constant):
            continue
        if not isinstance(first.value.value, str) or first.end_lineno is None:
            continue
        if first.end_lineno > first.lineno:
            lines.extend(range(first.lineno, first.end_lineno + 1))
    return lines


def strip_markers(segment: str) -> str:
    """Comment body without its //, /*, *, */ or # markers."""
    body = MARKER_RE.sub("", segment.strip(), count=1)
    return re.sub(r"\*+/$", "", body).strip()


def is_directive(body: str, line: int) -> bool:
    """True when the whole body is a machine directive with no trailing prose."""
    if line <= HEADER_LINES and any(r.fullmatch(body) for r in HEADER_RES):
        return True
    pieces = [piece for piece in re.split(r"\s*#+\s*", body) if piece]
    return bool(pieces) and all(any(r.fullmatch(p) for r in DIRECTIVE_RES) for p in pieces)


def segment_verdict(segment: str, line: int) -> str:
    """One of counted, exempt, or malformed for a single comment segment."""
    if line == 1 and segment.lstrip().startswith("#!"):
        return "exempt"
    body = strip_markers(segment)
    if body.startswith("DATASHEET:"):
        return "exempt" if DATASHEET_RE.fullmatch(body) else "malformed"
    return "exempt" if is_directive(body, line) else "counted"


def language_of(path: str, first_line: str) -> str | None:
    """Language key for a path, or None when it is not checked."""
    name = PurePosixPath(path).name
    suffix = PurePosixPath(path).suffix.lower()
    if suffix in CXX_SUFFIXES:
        return "cxx"
    if suffix in JS_SUFFIXES:
        return "js"
    if name == "CMakeLists.txt":
        return "cmake"
    if suffix or not first_line.startswith("#!"):
        return SUFFIX_LANGUAGES.get(suffix)
    if "python" in first_line:
        return "python"
    return "shell" if re.search(r"\b(?:ba|da|z)?sh\b", first_line) else None


def is_excluded(path: str) -> bool:
    """True for vendored, generated, and data paths."""
    parts = PurePosixPath(path).parts
    if path.startswith(EXCLUDE_PREFIXES) or path in EXCLUDE_FILES:
        return True
    if any(part in EXCLUDE_PARTS for part in parts):
        return True
    return parts[:1] == ("web",) and parts[-1] == "protocol.ts"


def is_scanned(path: str, head: str) -> bool:
    """True when the checker counts comments in this path, given its first lines."""
    if is_excluded(path) or GENERATED_RE.search(head):
        return False
    return language_of(path, head.split("\n")[0]) is not None


def analyze(path: str, text: str) -> FileResult | None:
    """Count the comment lines of one file, or None when it is not scanned."""
    lines = text.split("\n")
    language = language_of(path, lines[0])
    if language is None or not is_scanned(path, "\n".join(lines[:GENERATED_HEAD_LINES])):
        return None
    if language == "python":
        segments, docstrings = python_segments(text)
    else:
        segments, docstrings = spans_to_segments(text, SCANNERS[language](text)), []
    counted = [(line, "docstring") for line in docstrings]
    malformed: list[int] = []
    for line, parts in segments.items():
        verdicts = {segment_verdict(part, line) for part in parts}
        if "malformed" in verdicts:
            malformed.append(line)
        elif "counted" in verdicts:
            counted.append((line, "comment"))
    return FileResult(path, lines, sorted(counted), sorted(malformed))


def blocks(result: FileResult) -> list[dict[str, object]]:
    """Group consecutive counted lines of the same kind into blocks."""
    out: list[dict[str, object]] = []
    for line, kind in result.counted:
        last = out[-1] if out else None
        if last and last["kind"] == kind and last["end"] == line - 1:
            last["end"] = line
            last["text"] = f"{last['text']}\n{result.text(line)}"
        else:
            out.append(
                {
                    "path": result.path,
                    "start": line,
                    "end": line,
                    "kind": kind,
                    "text": result.text(line),
                }
            )
    return out


class Repo:
    """Git queries and file access rooted at one checkout."""

    def __init__(self, root: Path) -> None:
        self.root = root

    def git(self, *args: str, check: bool = True) -> str:
        """Run git in the checkout and return stdout."""
        result = subprocess.run(
            ["git", "-C", str(self.root), *args], capture_output=True, text=True, check=check
        )
        return result.stdout

    def tracked(self) -> list[str]:
        """Tracked and untracked, unignored paths that exist in the working tree."""
        paths = self.git("ls-files", "-z", "-co", "--exclude-standard").split("\0")
        return sorted(p for p in paths if p and (self.root / p).is_file())

    def staged(self) -> list[str]:
        """Paths added, copied, modified, or renamed in the index."""
        out = self.git("diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR")
        return [p for p in out.split("\0") if p]

    def read_worktree(self, path: str) -> str | None:
        """Working-tree text of a path, or None when missing or binary."""
        file = self.root / path
        return _decode(file.read_bytes()) if file.is_file() else None

    def read_rev(self, rev: str, path: str) -> str | None:
        """Text of a path at a revision (':' for the index), or None."""
        spec = f"{rev}:{path}" if rev != ":" else f":{path}"
        result = subprocess.run(
            ["git", "-C", str(self.root), "show", spec], capture_output=True, check=False
        )
        return _decode(result.stdout) if result.returncode == 0 else None

    def renames(self, cached: bool) -> dict[str, str]:
        """New path to old path for renames since the baseline last changed."""
        pairs: list[tuple[str, str]] = []
        since = self.git("log", "-1", "--format=%H", "--", BASELINE_NAME, check=False).strip()
        if since:
            log_args = ["log", "-M", "--diff-filter=R", "--name-status", "-z", "--format="]
            log = self.git(*log_args, "--reverse", f"{since}..HEAD", check=False)
            pairs += _rename_pairs(log)
        diff_args = ["diff", "-M", "--name-status", "-z", "--diff-filter=R"]
        diff_args += ["--cached"] if cached else []
        pairs += _rename_pairs(self.git(*diff_args, "HEAD", check=False))
        return {new: old for old, new in pairs}


def _rename_pairs(output: str) -> list[tuple[str, str]]:
    fields = [f for f in output.split("\0") if f]
    pairs: list[tuple[str, str]] = []
    i = 0
    while i + 2 < len(fields) and fields[i].startswith("R"):
        pairs.append((fields[i + 1], fields[i + 2]))
        i += 3
    return pairs


def _decode(data: bytes) -> str | None:
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", errors="replace")


def load_baseline(text: str | None) -> dict[str, int]:
    """Parse the baseline JSON, empty when absent."""
    return {str(k): int(v) for k, v in json.loads(text).items()} if text else {}


def budget_of(path: str, baseline: dict[str, int], renames: dict[str, str]) -> int:
    """Budget of a path, following renames back to a baselined origin."""
    if path in SELF_PATHS:
        return 0
    seen: set[str] = set()
    while path not in baseline and path in renames and path not in seen:
        seen.add(path)
        path = renames[path]
    return baseline.get(path, 0)


def new_lines(repo: Repo, result: FileResult) -> list[int]:
    """Counted lines whose text does not appear among HEAD's counted lines."""
    old_text = repo.read_rev("HEAD", result.path)
    old = analyze(result.path, old_text) if old_text is not None else None
    old_texts = Counter(old.text(line) for line, _ in old.counted) if old else Counter[str]()
    fresh: list[int] = []
    for line, _ in result.counted:
        text = result.text(line)
        if old_texts[text] > 0:
            old_texts[text] -= 1
        else:
            fresh.append(line)
    return fresh or [line for line, _ in result.counted]


def check(
    repo: Repo, paths: list[str], read: Reader, baseline: dict[str, int], renames: dict[str, str]
) -> list[str]:
    """Problems for the given paths; empty when every file is within budget."""
    problems = [
        f"{p}: the checker's own files have a budget of 0 and cannot be baselined"
        for p in SELF_PATHS
        if p in baseline
    ]
    for path in paths:
        text = read(path)
        result = analyze(path, text) if text is not None else None
        if result is None:
            continue
        problems += [
            f"{path}:{line}: malformed DATASHEET line, expected "
            f"'DATASHEET: <doc> rev <N>, <table N|N.N.N|p. N|fig. N>: <fact>'\n"
            f"    {result.text(line)}"
            for line in result.malformed
        ]
        budget = budget_of(path, baseline, renames)
        if result.count > budget:
            shown = new_lines(repo, result)
            listing = "".join(
                f"\n    {line}: {result.text(line)}" for line in shown[:SHOWN_LINES_LIMIT]
            )
            more = len(shown) - SHOWN_LINES_LIMIT
            listing += f"\n    ... {more} more" if more > 0 else ""
            problems.append(f"{path}: {result.count} comment lines, budget {budget}{listing}")
    return problems


