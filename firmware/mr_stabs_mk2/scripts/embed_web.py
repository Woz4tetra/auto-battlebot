# noqa: INP001  (PlatformIO extra script: SCons execs it, nothing imports it)
"""PlatformIO pre-build step: gzip web/ into a C header the diagnostics server serves.

Writes web_assets.h into the build directory and puts that directory on the include path, so
nothing generated lands in the source tree. The header is rewritten only when its content
changes, so an untouched web/ does not trigger a recompile. gzip runs with mtime 0 to keep the
output byte-identical between builds.
"""

import gzip
from pathlib import Path

Import("env")  # noqa: F821  (SCons builtin)

CONTENT_TYPES = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".woff2": "font/woff2",
}

# Fonts never change between builds; everything else ships with the firmware it belongs to.
CACHEABLE = {".woff2"}


def c_name(rel: Path) -> str:
    return "asset_" + "".join(c if c.isalnum() else "_" for c in rel.as_posix())


def render(web_dir: Path) -> str:
    files = sorted(p for p in web_dir.rglob("*") if p.is_file() and p.suffix in CONTENT_TYPES)
    if not any(p.name == "index.html" for p in files):
        raise RuntimeError(f"embed_web: no index.html in {web_dir}")

    lines = [
        "// Generated by scripts/embed_web.py from web/. Do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "namespace web_assets {",
        "",
        "struct asset_t {",
        "    const char *path;",
        "    const char *content_type;",
        "    const uint8_t *data;  // gzip",
        "    size_t length;",
        "    bool cacheable;",
        "};",
        "",
    ]
    entries = []
    for path in files:
        rel = path.relative_to(web_dir)
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        name = c_name(rel)
        lines.append(f"// {rel.as_posix()}: {path.stat().st_size} B, {len(data)} B gzipped")
        lines.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 20):
            lines.append("    " + ",".join(str(b) for b in data[i : i + 20]) + ",")
        lines.append("};")
        url = "/" if rel.as_posix() == "index.html" else "/" + rel.as_posix()
        cacheable = "true" if path.suffix in CACHEABLE else "false"
        entries.append(
            f'    {{"{url}", "{CONTENT_TYPES[path.suffix]}", {name}, sizeof({name}), {cacheable}}},'
        )
    lines += [
        "",
        "static const asset_t ASSETS[] = {",
        *entries,
        "};",
        "",
        "}  // namespace web_assets",
        "",
    ]
    return "\n".join(lines)


project_dir = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
out_dir = Path(env.subst("$BUILD_DIR")) / "web_assets"  # noqa: F821
out_dir.mkdir(parents=True, exist_ok=True)
header = out_dir / "web_assets.h"
text = render(project_dir / "web")
if not header.exists() or header.read_text() != text:
    header.write_text(text)
    print(f"embed_web: wrote {header}")
env.Append(CPPPATH=[str(out_dir)])  # noqa: F821
