TEST(MotionProfileGoldenTest, BodyVelocityShapesBackToTheStickOutputBeforeTheUnitChange) {
    auto clock = std::make_shared<ManualClock>();
    const MotionProfileNavigationConfiguration config = nav_golden::scenario_config();
    MotionProfileNavigation nav(config, clock);
    nav.initialize();
    const PlantCommandShaper shaper(config.plant, 1.0);
    for (int i = 0; i < nav_golden::kScenarioTicks; ++i) {
        auto tick = nav_golden::scenario_tick(i);
        clock->set(tick.time_s);
        const VelocityCommand body = nav.update(tick.robots, tick.field, tick.target);
        const GoldenStick &golden = kStickOutputAtEc9c37c8[static_cast<size_t>(i)];

        const StickCommand unsaturated = plant_body_velocity_to_stick(body, config.plant);
        EXPECT_NEAR(unsaturated.forward, golden.forward, 1e-12) << "tick " << i;
        EXPECT_NEAR(unsaturated.yaw, golden.yaw, 1e-12) << "tick " << i;

        const StickCommand sent = shaper.shape(body);
        const StickCommand golden_sent =
            saturate_stick({.forward = golden.forward, .lateral = 0.0, .yaw = golden.yaw}, 1.0);
        EXPECT_NEAR(sent.forward, golden_sent.forward, 1e-12) << "tick " << i;
        EXPECT_NEAR(sent.yaw, golden_sent.yaw, 1e-12) << "tick " << i;
    }
}

